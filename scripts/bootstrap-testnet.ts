/**
 * Provisions everything Plimsoll needs on Stellar testnet and writes apps/web/.env.local:
 * relayer + demo issuer, the demo asset and its Stellar Asset Contract, funded demo personas
 * with trustlines, and the uploaded escrow wasm hash. Safe to re-run; existing keys are reused.
 */
import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import { Asset, Keypair } from "@stellar/stellar-sdk";
import { parseAmount } from "@plimsoll/domain";
import { EscrowGateway, accountExists, buildChangeTrust, friendbotFund, hasTrustline, issuePayment, resolveNetwork, tokenBalance } from "@plimsoll/stellar";
import { readEnvFile, writeEnvFile } from "./env-file";

const ROOT = resolve(import.meta.dirname, "..");
const ENV_PATH = resolve(ROOT, "apps/web/.env.local");
const WASM_PATH = resolve(ROOT, "contracts/target/wasm32v1-none/release/plimsoll_trade_escrow.wasm");
const ASSET_CODE = "DEMOUSD";
const BUYER_FLOAT = parseAmount("2000000");

const PERSONAS = ["BUYER", "SUPPLIER", "INSPECTOR", "FORWARDER", "RESOLVER"] as const;
const NEEDS_TRUSTLINE = new Set(["BUYER", "SUPPLIER"]);

function keyFor(env: Record<string, string>, name: string): Keypair {
  const existing = env[name];
  return existing ? Keypair.fromSecret(existing) : Keypair.random();
}

async function ensureFunded(gw: EscrowGateway, kp: Keypair, label: string): Promise<void> {
  if (await accountExists(gw, kp.publicKey())) return;
  console.log(`  funding ${label} ${kp.publicKey()} via friendbot`);
  await friendbotFund(gw, kp.publicKey());
}

async function main(): Promise<void> {
  const env = readEnvFile(ENV_PATH);
  const network = resolveNetwork(env.STELLAR_NETWORK ?? "testnet", env.STELLAR_RPC_URL || undefined);
  if (network.id === "mainnet") throw new Error("Bootstrap creates demo assets and keys; it refuses to run against mainnet.");

  const relayer = keyFor(env, "PLIMSOLL_RELAYER_SECRET");
  const issuer = keyFor(env, "PLIMSOLL_ISSUER_SECRET");
  const personas = Object.fromEntries(PERSONAS.map((p) => [p, keyFor(env, `DEMO_${p}_SECRET`)])) as Record<(typeof PERSONAS)[number], Keypair>;
  const gw = new EscrowGateway(network, relayer);
  const header = "# Generated by scripts/bootstrap-testnet.ts. Testnet-only demo secrets. Never commit.";
  writeEnvFile(
    ENV_PATH,
    {
      STELLAR_NETWORK: network.id,
      PLIMSOLL_RELAYER_SECRET: relayer.secret(),
      PLIMSOLL_ISSUER_SECRET: issuer.secret(),
      ...Object.fromEntries(PERSONAS.map((p) => [`DEMO_${p}_SECRET`, personas[p].secret()])),
    },
    header,
  );

  console.log(`Bootstrapping Plimsoll on ${network.label} (${network.rpcUrl})`);
  await ensureFunded(gw, relayer, "relayer");
  await ensureFunded(gw, issuer, "demo issuer");
  for (const [name, kp] of Object.entries(personas)) await ensureFunded(gw, kp, name.toLowerCase());

  const asset = { code: ASSET_CODE, issuer: issuer.publicKey() };
  for (const name of PERSONAS) {
    if (!NEEDS_TRUSTLINE.has(name)) continue;
    const kp = personas[name];
    if (await hasTrustline(gw, kp.publicKey(), asset)) continue;
    console.log(`  adding ${ASSET_CODE} trustline for ${name.toLowerCase()}`);
    const tx = await buildChangeTrust(gw, kp.publicKey(), asset);
    tx.sign(kp);
    await gw.sendAndPoll(tx);
  }

  const balance = await tokenBalance(gw, personas.BUYER.publicKey(), asset);
  if (balance < BUYER_FLOAT) {
    console.log(`  issuing ${ASSET_CODE} float to buyer`);
    await issuePayment(gw, issuer, personas.BUYER.publicKey(), asset, BUYER_FLOAT - balance);
  }

  console.log("  ensuring Stellar Asset Contract");
  const tokenContractId = await gw.ensureAssetContract(new Asset(asset.code, asset.issuer));

  console.log("  uploading escrow wasm");
  const wasmHash = await gw.uploadWasm(readFileSync(WASM_PATH));

  writeEnvFile(
    ENV_PATH,
    {
      PLIMSOLL_ASSET_CODE: asset.code,
      PLIMSOLL_ASSET_ISSUER: asset.issuer,
      PLIMSOLL_ASSET_IS_DEMO: "true",
      PLIMSOLL_TOKEN_CONTRACT_ID: tokenContractId,
      PLIMSOLL_ESCROW_WASM_HASH: wasmHash,
    },
    header,
  );

  console.log("\nDone.");
  console.log(`  token contract   ${tokenContractId} (${ASSET_CODE}, demo token, not USDC)`);
  console.log(`  escrow wasm hash ${wasmHash}`);
  console.log(`  relayer          ${relayer.publicKey()}`);
  for (const p of PERSONAS) console.log(`  ${p.toLowerCase().padEnd(16)} ${personas[p].publicKey()}`);
  console.log(`\nWrote ${ENV_PATH}`);
}

main().catch((e: unknown) => {
  console.error(e);
  process.exit(1);
});
